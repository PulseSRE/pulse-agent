def _evidence_view(result: dict) -> list[dict]:
    from sre_agent.inbox import investigation_metadata
    from sre_agent.view_executor import _build_header_widgets

    return _build_header_widgets({"metadata": investigation_metadata(result, "i-contract")})


def _investigation_report(result: dict) -> dict:
    """The investigation_report a plan broadcasts (investigation_pipeline.outcome_from_plan)."""
    from sre_agent.monitor.investigation_pipeline import outcome_from_plan
    from sre_agent.skill_plan import PlanResult, SkillOutput

    diagnose = SkillOutput(
        skill_id="sre",
        phase_id="diagnose",
        findings={
            "root_cause": result["suspected_cause"],
            "alternatives_considered": result["alternatives_considered"],
        },
        evidence_summary=result["summary"],
        confidence=result["confidence"],
        evidence=result["evidence_detail"],
    )
    template = SimpleNamespace(
        id="crashloop-resolution-v1",
        phases=[SimpleNamespace(id="diagnose", produces=["root_cause", "confidence"])],
    )
    plan = PlanResult(plan_id=template.id, plan_name="Crashloop Resolution", phases_total=1)
    plan.status = "complete"
    plan.phase_outputs = {"diagnose": diagnose}
    finding = {"id": "f-contract", "category": "crashloop", "resources": []}

    report = outcome_from_plan(template, plan).to_report(finding)
    assert report is not None
    # Generated per run; pinned so the golden compares.
    return {**report, "id": "i-contract", "timestamp": 1761600000000}


def build_contract() -> dict:
    return {
        "_comment": (
            "Generated by pulse-agent tests/test_ui_contract_fixtures.py from the agent's real code. "
            "Do not edit by hand; copy to pulse-ui src/kubeview/__fixtures__/agent-contract/investigation.json."
        ),
        "evidence_view": {"supported": _evidence_view(SUPPORTED), "unsupported": _evidence_view(UNSUPPORTED)},
        "investigation_report": {
            "supported": _investigation_report(SUPPORTED),
            "unsupported": _investigation_report(UNSUPPORTED),
        },
    }


def test_ui_contract_matches_what_the_agent_emits():
    current = json.loads(json.dumps(build_contract(), sort_keys=True))
    if os.environ.get("UPDATE_UI_CONTRACT"):
        GOLDEN.parent.mkdir(parents=True, exist_ok=True)
        GOLDEN.write_text(json.dumps(current, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
    assert current == golden, (
        "The agent's investigation payloads changed. Regenerate with UPDATE_UI_CONTRACT=1 and copy the file "
        "to pulse-ui src/kubeview/__fixtures__/agent-contract/investigation.json."
    )


def test_contract_keeps_the_cases_the_ui_must_draw():
    contract = build_contract()
    supported = contract["evidence_view"]["supported"]
    kinds = [w["kind"] for w in supported]
    assert kinds == ["confidence_badge", "info_card_grid", "status_list", "info_card_grid"]
    statuses = {i["status"] for i in supported[2]["props"]["items"]}
    assert len(statuses) == 3, "supports, contradicts and context must render differently"
    # Nothing supports the unsupported case, and it still says so with a 0.
    unsupported = contract["evidence_view"]["unsupported"]
    assert unsupported[0] == {"kind": "confidence_badge", "title": "Investigation Confidence", "props": {"score": 0.0}}
    report = contract["investigation_report"]["supported"]
    assert report["evidenceDetail"][2]["stance"] == "contradicts"
